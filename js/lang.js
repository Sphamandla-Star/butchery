/* ---------- Apply translations to the page ---------- */
function applyLang(lang) {
    const strings = translations[lang] || translations.en;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.getAttribute("data-i18n");
        if (strings[key] !== undefined) {
            el.textContent = strings[key];
        }
    });

    // Update placeholder attributes
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (strings[key] !== undefined) {
            el.placeholder = strings[key];
        }
    });

    document.documentElement.lang = lang === "zu" ? "zu" : "en";
    localStorage.setItem(LANG_KEY, lang);

    // Update toggle button label
    const btn = document.getElementById("lang-toggle");
    if (btn) {
        btn.textContent = lang === "zu" ? "EN" : "ZU";
        btn.setAttribute("aria-label", lang === "zu" ? "Switch to English" : "Shintsha isiZulu");
        btn.setAttribute("data-lang", lang);
    }
}

/* ---------- Init ---------- */
document.addEventListener("DOMContentLoaded", () => {
    const saved = localStorage.getItem(LANG_KEY) || "en";
    applyLang(saved);

    const btn = document.getElementById("lang-toggle");
    if (btn) {
        btn.addEventListener("click", () => {
            const current = localStorage.getItem(LANG_KEY) || "en";
            applyLang(current === "en" ? "zu" : "en");
        });
    }
});
